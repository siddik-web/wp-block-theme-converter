#!/usr/bin/env node
// Lint block markup in templates/, parts/, and patterns/ for common anti-patterns.

import { readFileSync } from 'fs';
import { resolve, join, extname, relative } from 'path';
import { collectFiles, lineAt, blankPhp, tokenizeBlocks } from './lib/theme-utils.mjs';

const themeDir = resolve(process.argv[2] ?? '.');

const scanDirs = ['templates', 'parts', 'patterns'];
const files = scanDirs.flatMap(d => collectFiles(join(themeDir, d), ['.html', '.php']));

// violations: { file, line, message }
const violations = [];
const filesWithViolations = new Set();

function report(file, line, message) {
  const rel = relative(themeDir, file);
  console.log(`${rel}:${line}: ${message}`);
  violations.push({ file, line, message });
  filesWithViolations.add(file);
}

// An HTML start tag carrying a style="" attribute.
const STYLE_ATTR_RE = /<[a-zA-Z][a-zA-Z0-9-]*\b[^>]*?\sstyle\s*=\s*(["'])([\s\S]*?)\1/g;
const STYLE_TAG_RE = /<style[\s>]/gi;
const SCRIPT_TAG_RE = /<script[\s>]/gi;
// PHP: echo $var not followed by esc_
const ECHO_UNESCAPED_RE = /echo\s+\$[a-zA-Z]/;
const ECHO_ESC_RE = /echo\s+esc_/;
// Physical (non-logical) directional CSS properties.
const DIRECTIONAL_RE = /(?:margin|padding)-(?:left|right)\s*:|text-align\s*:\s*(?:left|right)/i;

/** Innermost open block containing `index`, or null when outside any block. */
function enclosingBlock(tokens, index) {
  const stack = [];
  for (const tok of tokens) {
    if (tok.index >= index) break;
    if (tok.type === 'open') stack.push(tok);
    else if (tok.type === 'close') {
      const at = stack.map(t => t.name).lastIndexOf(tok.name);
      if (at !== -1) stack.length = at;
    }
  }
  return stack[stack.length - 1] ?? null;
}

for (const file of files) {
  const ext = extname(file).toLowerCase();
  const raw = readFileSync(file, 'utf8');
  // PHP blocks are blanked (offsets preserved) so PHP code isn't mistaken for markup.
  const src = ext === '.php' ? blankPhp(raw) : raw;
  const tokens = tokenizeBlocks(src);

  // ── Inline style attributes ──────────────────────────────────────────────
  // Core serializes block-support styles (spacing, typography, …) as inline
  // style="" on the block's wrapper, so a style attribute inside a block that
  // declares attributes is expected. A style attribute outside any block,
  // inside core/html, or inside a block with no attributes was hand-written.
  let m;
  while ((m = STYLE_ATTR_RE.exec(src)) !== null) {
    const block = enclosingBlock(tokens, m.index);
    const handWritten = !block || block.name === 'html' || block.name === 'core/html' || !block.attrs;
    if (!handWritten) continue;
    const line = lineAt(src, m.index);
    report(file, line, 'Hand-written inline style="" attribute (not generated by block supports) — use block supports or theme.json instead');
    if (DIRECTIONAL_RE.test(m[2])) {
      report(file, line, 'Physical CSS directional property in style attribute — use logical properties (margin-inline-start, etc.)');
    }
  }

  for (const [re, message] of [
    [STYLE_TAG_RE, '<style> tag found in block markup — enqueue via wp_enqueue_style instead'],
    [SCRIPT_TAG_RE, '<script> tag found in block markup — enqueue via wp_enqueue_script instead'],
  ]) {
    while ((m = re.exec(src)) !== null) report(file, lineAt(src, m.index), message);
  }

  // ── PHP echo without escaping ────────────────────────────────────────────
  if (ext === '.php') {
    raw.split('\n').forEach((line, i) => {
      if (ECHO_UNESCAPED_RE.test(line) && !ECHO_ESC_RE.test(line)) {
        report(file, i + 1, 'Possibly unescaped echo of variable — wrap with esc_html(), esc_attr(), etc.');
      }
    });
  }

  // ── Block delimiter integrity ────────────────────────────────────────────
  const stack = [];
  for (const tok of tokens) {
    if (tok.type === 'void') continue;
    if (tok.type === 'open') {
      stack.push(tok);
      continue;
    }
    const at = stack.map(t => t.name).lastIndexOf(tok.name);
    if (at === -1) {
      report(file, lineAt(src, tok.index), `Unmatched closing block comment <!-- /wp:${tok.name} --> (no open tag on stack)`);
      continue;
    }
    // Anything opened after the matching opener was never closed.
    const [, ...unclosedInside] = stack.splice(at);
    for (const unclosed of unclosedInside) {
      report(file, lineAt(src, unclosed.index), `Unclosed block comment <!-- wp:${unclosed.name} --> (closed implicitly by <!-- /wp:${tok.name} --> at line ${lineAt(src, tok.index)})`);
    }
  }
  for (const unclosed of stack) {
    report(file, lineAt(src, unclosed.index), `Unclosed block comment <!-- wp:${unclosed.name} --> has no matching <!-- /wp:${unclosed.name} -->`);
  }
}

// ── Summary ───────────────────────────────────────────────────────────────────
const totalFiles = files.length;
const violationFiles = filesWithViolations.size;
console.log(`\nScanned ${totalFiles} file(s). ${violations.length} violation(s) in ${violationFiles} file(s).`);
process.exit(violationFiles);
